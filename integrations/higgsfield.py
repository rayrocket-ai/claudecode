"""Higgsfield Cloud API client for image-to-video generation.

Uses the official `higgsfield-client` SDK (https://pypi.org/project/higgsfield-client/).
Authentication is via an API key + secret pair set as environment variables
HF_API_KEY and HF_API_SECRET, obtained from https://cloud.higgsfield.ai/api-keys.

Walkthrough-style tour videos are generated by submitting each listing photo
to a Higgsfield image-to-video endpoint along with a room-specific prompt
and camera motion preset.
"""

from __future__ import annotations

import asyncio
import logging
import os
from pathlib import Path
from typing import Any

import httpx

from config import get_settings

logger = logging.getLogger(__name__)

# Default image-to-video endpoint. Higgsfield hosts several — switch via env
# (HIGGSFIELD_I2V_ENDPOINT) if needed (e.g. "higgsfield/soul/v1/image-to-video",
# "higgsfield/dop/v1/image-to-video", etc).
DEFAULT_I2V_ENDPOINT = "higgsfield/dop/v1/image-to-video"

# Camera motion presets for realistic walkthrough feel
WALKTHROUGH_MOTIONS = [
    {"type": "push_in", "description": "Slow push-in toward the subject"},
    {"type": "pan_right", "description": "Gentle pan right to reveal the space"},
    {"type": "pan_left", "description": "Gentle pan left to reveal the space"},
    {"type": "tilt_up", "description": "Tilt up to show ceiling/height"},
    {"type": "dolly_forward", "description": "Dolly forward into the room"},
    {"type": "orbit_right", "description": "Subtle orbit around the subject"},
    {"type": "zoom_out", "description": "Slow zoom out to reveal full space"},
    {"type": "crane_up", "description": "Crane up for elevated perspective"},
]

# Room-type prompts for better video generation
ROOM_PROMPTS = {
    "exterior": "Cinematic establishing shot of a residential property exterior, smooth camera movement, golden hour lighting, real estate showcase",
    "living": "Smooth walkthrough of a spacious living room, warm natural lighting, cinematic camera movement, real estate video tour",
    "kitchen": "Cinematic pan across a modern kitchen, revealing countertops and appliances, warm lighting, real estate showcase",
    "bedroom": "Gentle dolly into a bright bedroom, soft natural light through windows, smooth camera motion, real estate tour",
    "bathroom": "Elegant reveal of a clean bathroom, smooth camera pan, bright lighting, real estate showcase",
    "dining": "Cinematic sweep of a dining area, warm ambient lighting, smooth camera movement, real estate video",
    "backyard": "Sweeping view of the backyard and outdoor space, natural lighting, cinematic drone-style movement",
    "default": "Smooth cinematic walkthrough of a room interior, natural lighting, professional real estate video tour, steady camera movement",
}


def _configure_sdk_credentials() -> None:
    """Ensure HF_API_KEY / HF_API_SECRET env vars are set from Settings."""
    settings = get_settings()

    # SDK reads from env vars at call time; set them if our Settings has values
    api_key = settings.higgsfield_api_key
    api_secret = getattr(settings, "higgsfield_api_secret", "")

    if api_key and api_secret:
        os.environ["HF_API_KEY"] = api_key
        os.environ["HF_API_SECRET"] = api_secret
    elif api_key and ":" in api_key:
        # Combined form (key:secret) — set as HF_KEY directly
        os.environ["HF_KEY"] = api_key
    elif api_key:
        # Only a single key provided — SDK may not accept it, but try
        os.environ["HF_API_KEY"] = api_key

    if not (os.environ.get("HF_KEY") or
            (os.environ.get("HF_API_KEY") and os.environ.get("HF_API_SECRET"))):
        raise ValueError(
            "Higgsfield credentials not configured. "
            "Set HIGGSFIELD_API_KEY and HIGGSFIELD_API_SECRET in .env."
        )


class HiggsFieldClient:
    """Async client wrapping the official higgsfield-client SDK."""

    def __init__(self, endpoint: str | None = None):
        _configure_sdk_credentials()
        # Import lazily so import errors surface clearly
        import higgsfield_client as hf
        self._hf = hf
        self._async_client = hf.AsyncClient()
        self.endpoint = endpoint or os.getenv(
            "HIGGSFIELD_I2V_ENDPOINT", DEFAULT_I2V_ENDPOINT
        )

    async def upload_image(self, image_path: Path | str) -> str:
        """Upload a local image and return its hosted URL."""
        image_path = Path(image_path)
        if not image_path.exists():
            raise FileNotFoundError(f"Image not found: {image_path}")
        url = await self._async_client.upload_file(str(image_path))
        logger.info("Uploaded %s -> %s", image_path.name, url)
        return url

    async def generate_video_from_image(
        self,
        image_path: Path | str,
        *,
        prompt: str = "",
        motion_type: str = "push_in",
        duration: int = 5,
        model: str = "standard",
    ) -> dict[str, Any]:
        """Submit an image-to-video generation request and wait for completion.

        Returns the full result dict from the SDK (contains the output video URL).
        """
        if not prompt:
            prompt = ROOM_PROMPTS["default"]

        image_url = await self.upload_image(image_path)

        arguments = {
            "prompt": prompt,
            "image_url": image_url,
            "motion_type": motion_type,
            "duration": duration,
            "model": model,
            "camera_fixed": False,
        }

        logger.info(
            "Submitting Higgsfield generation: endpoint=%s motion=%s duration=%d",
            self.endpoint, motion_type, duration,
        )

        result = await self._async_client.subscribe(
            self.endpoint,
            arguments=arguments,
            on_enqueue=lambda rid: logger.info("Enqueued request %s", rid),
            on_queue_update=lambda status: logger.debug(
                "Status: %s", status.__class__.__name__
            ),
        )
        return result

    async def download_video(
        self,
        generation_result: dict[str, Any],
        output_path: Path | str,
    ) -> Path:
        """Download the generated video to a local file."""
        output_path = Path(output_path)

        # Probe several possible response shapes
        video_url = None
        if isinstance(generation_result, dict):
            video_url = (
                generation_result.get("video_url")
                or generation_result.get("video", {}).get("url") if isinstance(generation_result.get("video"), dict) else None
            )
            if not video_url:
                video_url = generation_result.get("output", {}).get("video_url") if isinstance(generation_result.get("output"), dict) else None
            if not video_url:
                # Look for the first url-like field containing .mp4
                for key, val in generation_result.items():
                    if isinstance(val, str) and ".mp4" in val:
                        video_url = val
                        break
                    if isinstance(val, dict):
                        for sub_val in val.values():
                            if isinstance(sub_val, str) and ".mp4" in sub_val:
                                video_url = sub_val
                                break

        if not video_url:
            raise ValueError(f"No video URL in result: {generation_result}")

        async with httpx.AsyncClient(timeout=120.0) as client:
            resp = await client.get(video_url, follow_redirects=True)
            resp.raise_for_status()
            output_path.write_bytes(resp.content)

        logger.info("Downloaded video to %s (%d bytes)", output_path, output_path.stat().st_size)
        return output_path

    async def generate_and_download(
        self,
        image_path: Path | str,
        output_path: Path | str,
        *,
        prompt: str = "",
        motion_type: str = "push_in",
        duration: int = 5,
        model: str = "standard",
    ) -> Path:
        """Submit, wait, and download in one call."""
        result = await self.generate_video_from_image(
            image_path,
            prompt=prompt,
            motion_type=motion_type,
            duration=duration,
            model=model,
        )
        return await self.download_video(result, output_path)


async def test_connection() -> dict[str, Any]:
    """Quick connectivity / credential check. Returns status dict."""
    try:
        _configure_sdk_credentials()
    except ValueError as e:
        return {"ok": False, "error": str(e)}

    try:
        import higgsfield_client as hf
        # Probe with a fake request id — expect 404 if auth works, 401/403 if not
        client = hf.AsyncClient()
        try:
            await client.status("probe-00000000-0000-0000-0000-000000000000")
            return {"ok": True, "note": "Unexpected success"}
        except Exception as e:
            msg = str(e)
            if any(code in msg for code in ("401", "403")) or "unauthorized" in msg.lower():
                return {"ok": False, "error": f"Auth rejected: {msg[:200]}"}
            if "404" in msg or "not found" in msg.lower():
                return {"ok": True, "note": "Credentials accepted (expected 404 for fake id)"}
            return {"ok": False, "error": f"Unknown: {msg[:200]}"}
    except ImportError:
        return {"ok": False, "error": "higgsfield-client SDK not installed (pip install higgsfield-client)"}


def classify_room_from_index(index: int, total: int) -> str:
    """Heuristic to guess room type from photo order in a listing.

    Listings typically follow: exterior → living → kitchen → bedrooms → bathrooms → backyard.
    """
    if total <= 1:
        return "default"

    ratio = index / total

    if index == 0:
        return "exterior"
    elif ratio < 0.2:
        return "living"
    elif ratio < 0.35:
        return "kitchen"
    elif ratio < 0.55:
        return "bedroom"
    elif ratio < 0.7:
        return "bathroom"
    elif ratio < 0.85:
        return "dining"
    elif index == total - 1:
        return "backyard"
    else:
        return "default"
