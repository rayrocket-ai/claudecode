"""Fallback PDF builder using ReportLab when TransactionDesk is unavailable."""

from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path

from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors

from config import STORAGE_DIR, get_settings


def _safe(val, default=""):
    """Safely get a value, returning default if None/empty."""
    if val is None:
        return default
    return str(val).strip() or default


def generate_aps_pdf(deal_data: dict, output_path: str | None = None) -> str:
    """Generate an APS summary PDF (fallback — not the real OREA form)."""
    if output_path is None:
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_path = str(STORAGE_DIR / f"aps_summary_{ts}.pdf")

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    settings = get_settings()

    doc = SimpleDocTemplate(output_path, pagesize=letter,
                            topMargin=0.5 * inch, bottomMargin=0.5 * inch)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("Title2", parent=styles["Title"], fontSize=14)
    subtitle_style = ParagraphStyle("Subtitle2", parent=styles["Normal"],
                                    fontSize=10, textColor=colors.grey)

    elements = []

    # Header
    elements.append(Paragraph("AGREEMENT OF PURCHASE AND SALE", title_style))
    elements.append(Paragraph("SUMMARY — Generated by AI Assistant (Not the official OREA Form)",
                              subtitle_style))
    elements.append(Paragraph(f"Brokerage: {settings.brokerage_name}", subtitle_style))
    elements.append(Spacer(1, 0.3 * inch))

    # Property
    addr = f"{_safe(deal_data.get('property_street_number'))} {_safe(deal_data.get('property_street_name'))}"
    unit = deal_data.get("property_unit")
    if unit:
        addr += f", Unit {unit}"
    city = _safe(deal_data.get("property_city"))
    postal = _safe(deal_data.get("property_postal_code"))

    _add_section(elements, styles, "PROPERTY", [
        ("Address", addr),
        ("City", city),
        ("Postal Code", postal),
        ("MLS #", _safe(deal_data.get("mls_number"), "N/A")),
    ])

    # Parties
    _add_section(elements, styles, "PARTIES", [
        ("Buyer(s)", f"{_safe(deal_data.get('buyer_1'))}  {_safe(deal_data.get('buyer_2'))}".strip()),
        ("Seller(s)", f"{_safe(deal_data.get('seller_1'))}  {_safe(deal_data.get('seller_2'))}".strip()),
    ])

    # Financial
    _add_section(elements, styles, "FINANCIAL TERMS", [
        ("Purchase Price", f"${_safe(deal_data.get('purchase_price'), '0')}"),
        ("Deposit", f"${_safe(deal_data.get('deposit'), '0')}"),
        ("Deposit Holder", _safe(deal_data.get("deposit_holder"), "Listing Brokerage")),
    ])

    # Dates
    _add_section(elements, styles, "KEY DATES", [
        ("Offer Date", _safe(deal_data.get("offer_date"), "TBD")),
        ("Irrevocability", _safe(deal_data.get("irrevocability_date"), "TBD")),
        ("Closing Date", _safe(deal_data.get("closing_date"), "TBD")),
    ])

    # Conditions
    conditions = deal_data.get("conditions", [])
    if conditions:
        cond_text = "<br/>".join(f"• {c}" for c in conditions) if isinstance(conditions, list) else str(conditions)
        _add_section(elements, styles, "CONDITIONS", [("", cond_text)])

    # Inclusions / Exclusions
    incl = deal_data.get("inclusions", "")
    excl = deal_data.get("exclusions", "")
    if incl or excl:
        _add_section(elements, styles, "INCLUSIONS / EXCLUSIONS", [
            ("Inclusions", _safe(incl, "As per listing")),
            ("Exclusions", _safe(excl, "None")),
        ])

    # Footer
    elements.append(Spacer(1, 0.5 * inch))
    elements.append(Paragraph(
        "⚠️ This is a SUMMARY document only. The official OREA Form 100 must be "
        "used for the actual Agreement of Purchase and Sale. This summary was "
        "generated because TransactionDesk / WebForms was not available.",
        ParagraphStyle("Warning", parent=styles["Normal"], fontSize=8,
                       textColor=colors.red)
    ))

    doc.build(elements)
    return output_path


def _add_section(elements, styles, title, rows):
    """Add a titled section with key-value rows."""
    elements.append(Paragraph(f"<b>{title}</b>", styles["Heading3"]))
    data = []
    for label, value in rows:
        if label:
            data.append([Paragraph(f"<b>{label}:</b>", styles["Normal"]),
                         Paragraph(str(value), styles["Normal"])])
        else:
            data.append([Paragraph(str(value), styles["Normal"]), ""])

    if data:
        t = Table(data, colWidths=[2 * inch, 4.5 * inch])
        t.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        elements.append(t)
    elements.append(Spacer(1, 0.2 * inch))


