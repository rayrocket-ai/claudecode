def generate_summary_pdf(deal_data: dict, doc_type: str, td_links: dict | None = None) -> str:
    """Generate a summary PDF for any document type.

    Known doc types get titled, form-specific sections (DOC_SECTIONS);
    unknown types and any leftover keys fall back to a generic listing.

    td_links: optional dict with 'transaction_url' and 'form_url' from TransactionDesk.
    """
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_path = str(STORAGE_DIR / f"{doc_type}_summary_{ts}.pdf")
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    settings = get_settings()
    doc = SimpleDocTemplate(output_path, pagesize=letter,
                            topMargin=0.5 * inch, bottomMargin=0.5 * inch)
    styles = getSampleStyleSheet()

    title = DOC_TITLES.get(doc_type, f"{doc_type.upper()} — Document Summary")

    elements = []
    elements.append(Paragraph(f"<b>{title}</b>", styles["Title"]))
    elements.append(Paragraph(
        "SUMMARY — Generated by AI Assistant (Not the official OREA form)",
        ParagraphStyle("Subtitle3", parent=styles["Normal"], fontSize=10,
                       textColor=colors.grey),
    ))
    elements.append(Paragraph(f"Brokerage: {settings.brokerage_name}", styles["Normal"]))
    elements.append(Paragraph(f"Generated: {datetime.now().strftime('%B %d, %Y at %I:%M %p')}",
                              styles["Normal"]))
    elements.append(Spacer(1, 0.3 * inch))

    shown_keys: set[str] = {"collection_complete"}
    for section_title, rows in DOC_SECTIONS.get(doc_type, []):
        filled = []
        for label, key in rows:
            shown_keys.add(key)
            value = deal_data.get(key)
            if value not in (None, ""):
                filled.append((label, str(value)))
        if filled:
            _add_section(elements, styles, section_title, filled)

    # Anything collected but not covered by the sections above.
    leftovers = [
        (key.replace("_", " ").title(), value)
        for key, value in sorted(deal_data.items())
        if key not in shown_keys and value not in (None, "")
    ]
    if leftovers:
        section_title = "OTHER DETAILS" if doc_type in DOC_SECTIONS else "COLLECTED DATA"
        _add_section(elements, styles, section_title,
                     [(label, str(value)) for label, value in leftovers])

    # TransactionDesk links
    if td_links:
        elements.append(Spacer(1, 0.3 * inch))
        elements.append(Paragraph("<b>TransactionDesk Links:</b>", styles["Heading3"]))
        if td_links.get("transaction_url"):
            elements.append(Paragraph(f"Transaction: {td_links['transaction_url']}", styles["Normal"]))
        if td_links.get("form_url"):
            elements.append(Paragraph(f"Form: {td_links['form_url']}", styles["Normal"]))

    doc.build(elements)
    return output_path
